let currentLang = "en";

function format(template, params) {
	if (!params) return template;
	let out = template;
	for (const [k, v] of Object.entries(params)) {
		out = out.split(`{${k}}`).join(String(v));
	}
	return out;
}

/**
 * Translate a key in the current language.
 * Falls back to English, then to the key itself (so missing keys are visible
 * instead of silently blank).
 */
export function t(key, params) {
	const table = MESSAGES[currentLang] ?? MESSAGES.en;
	const template = table[key] ?? MESSAGES.en[key];
	if (template == null) return key;
	return format(template, params);
}

/** Plural-aware translate: picks `{key}_one` / `{key}_many`. */
export function tp(key, n, params = {}) {
	const suffix = n === 1 ? "_one" : "_many";
	return t(`${key}${suffix}`, { n, ...params });
}

/**
 * Translate a slash command description (key `cmdDesc.<name>`).
 * Returns `fallback` (the canonical English description) when no
 * translation exists, so prompt templates / extension commands work too.
 */
export function tCmd(name, fallback) {
	const key = `cmdDesc.${String(name ?? "").replace(/^\//, "")}`;
	const table = MESSAGES[currentLang] ?? MESSAGES.en;
	if (table[key] != null) return table[key];
	if (MESSAGES.en[key] != null) return MESSAGES.en[key];
	return fallback ?? key;
}

export function setLanguage(lang) {
	if (MESSAGES[lang]) currentLang = lang;
}

export function getLanguage() {
	return currentLang;
}
